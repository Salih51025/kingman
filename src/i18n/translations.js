export function flattenKeys(value, prefix = "") {
  return Object.entries(value).flatMap(([key, nested]) => {
    const path = prefix ? `${prefix}.${key}` : key;
    if (nested && typeof nested === "object") {
      return flattenKeys(nested, path);
    }
    return [path];
  });
}

export function translate(lang, path, params = {}) {
  const table = translations[lang] || translations.tr;
  const found = path.split(".").reduce((node, part) => node?.[part], table);
  if (typeof found !== "string") {
    return path;
  }
  return found.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
}
